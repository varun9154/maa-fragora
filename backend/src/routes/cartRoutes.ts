import { Router } from "express";

import {
  getCart,
  addToCart,
  updateCart,
  removeCartItem,
  clearCart,
} from "../controllers/cartController";

import { protect } from "../middlewares/authMiddleware";

const router = Router();

/*
|--------------------------------------------------------------------------
| CART ROUTES
|--------------------------------------------------------------------------
| Every cart operation belongs to a logged-in user.
|--------------------------------------------------------------------------
*/

/*
|--------------------------------------------------------------------------
| GET CART
|--------------------------------------------------------------------------
*/

router.get(
  "/",
  protect,
  getCart
);

/*
|--------------------------------------------------------------------------
| ADD TO CART
|--------------------------------------------------------------------------
*/

router.post(
  "/",
  protect,
  addToCart
);

/*
|--------------------------------------------------------------------------
| UPDATE CART ITEM
|--------------------------------------------------------------------------
*/

router.put(
  "/:productId",
  protect,
  updateCart
);

/*
|--------------------------------------------------------------------------
| REMOVE CART ITEM
|--------------------------------------------------------------------------
*/

router.delete(
  "/:productId",
  protect,
  removeCartItem
);

/*
|--------------------------------------------------------------------------
| CLEAR CART
|--------------------------------------------------------------------------
*/

router.delete(
  "/",
  protect,
  clearCart
);

export default router;